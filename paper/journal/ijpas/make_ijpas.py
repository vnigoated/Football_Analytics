"""IJPAS version: word counts for the title page and the Overleaf zip.

    python paper/journal/ijpas/make_ijpas.py

IJPAS counts "no more than 7,500 words, inclusive of tables, references, figure or table captions and endnotes"
and asks for a 200-word unstructured abstract. This script counts:

* main text: Introduction to the end, including tables, captions, end statements and the appendix (LaTeX commands
  and math removed, a citation or inline formula counted as one word);
* references: the printed fields of every cited .bib entry;
* the abstract separately.

It writes ``counts.tex`` (read by manuscript.tex) and ``paper/journal/ijpas_overleaf.zip`` with anonymous.tex,
authors.tex, manuscript.tex, counts.tex, refs.bib, figures/ and a README.
"""

import re
import zipfile
from pathlib import Path

HERE = Path(__file__).parent
TEX = HERE / "manuscript.tex"
BIB = HERE.parent.parent / "refs.bib"
FIGS = HERE.parent / "figures"
FIELDS = ("author", "title", "journal", "booktitle", "year", "volume", "number", "pages", "note", "howpublished",
          "publisher")


def words(s: str) -> int:
    s = re.sub(r"\\(cite[pt]?|citealp|ref|label|url)\{[^}]*\}", " X ", s)
    s = re.sub(r"\$[^$]*\$", " X ", s)
    s = re.sub(r"\\begin\{tabular\}\{[^}]*\}", " ", s)
    s = re.sub(r"\\[a-zA-Z]+\*?", " ", s)
    s = re.sub(r"[{}\[\]~&]", " ", s)
    return len([w for w in s.split() if re.search(r"[A-Za-z0-9]", w)])


def bib_entries(text: str) -> dict[str, str]:
    out = {}
    for m in re.finditer(r"@\w+\{([^,]+),", text):
        start, depth, j = m.end(), 1, m.end()
        while depth and j < len(text):
            depth += {"{": 1, "}": -1}.get(text[j], 0)
            j += 1
        out[m.group(1).strip()] = text[start:j - 1]
    return out


def field_text(entry: str) -> str:
    parts = []
    for f in FIELDS:
        m = re.search(rf"(?m)^\s*{f}\s*=\s*\{{(.*?)\}},?\s*$", entry, flags=re.DOTALL)
        if m:
            parts.append(m.group(1))
    return " ".join(parts).replace(" and ", " ")


def counts() -> tuple[int, int, int, int]:
    t = re.sub(r"(?m)(?<!\\)%.*$", "", TEX.read_text(encoding="utf-8"))
    abstract = t.split(r"\begin{abstract}")[1].split(r"\end{abstract}")[0]
    body = t.split(r"\section{Introduction}")[1]
    main, appendix = body.split(r"\bibliographystyle")[0], body.split(r"\appendix")[1]
    cited = {k.strip() for c in re.findall(r"\\cite\w*\{([^}]+)\}", t) for k in c.split(",")}
    bib = bib_entries(BIB.read_text(encoding="utf-8"))
    refs = sum(words(field_text(bib[k])) for k in cited if k in bib)
    main_n, app_n = words(main), words(appendix)
    return words(abstract), main_n, app_n, refs


def main() -> None:
    abstract, main_n, app_n, refs = counts()
    total = main_n + app_n + refs
    (HERE / "counts.tex").write_text(
        "% generated by make_ijpas.py\n"
        f"\\newcommand{{\\wordcount}}{{{total:,}}}\n\\newcommand{{\\abstractcount}}{{{abstract}}}\n",
        encoding="utf-8")
    print(f"abstract {abstract} | main text incl. tables/captions/statements {main_n} | appendix {app_n} | "
          f"references {refs} | total {total} (limit 7,500)")
    readme = f"""How to compile (Overleaf) - IJPAS version
==========================================

1. Overleaf -> New Project -> Templates -> "Taylor & Francis LaTeX template for authors (Interact layout +
   American Psychological Association reference style)" -> Open as Template.
2. Delete the template's sample .tex and .bib files (keep interact.cls and the other class/style files).
3. Unzip this file on your computer, then upload anonymous.tex, authors.tex, manuscript.tex, counts.tex and refs.bib.
   Create a folder "figures" and upload the 5 PDFs into it.
4. Compiler: pdfLaTeX.
   - Menu -> Main document: anonymous.tex -> Recompile -> download the PDF as "anonymous.pdf".
   - Menu -> Main document: authors.tex   -> Recompile -> download the PDF as "authors.pdf".
   Do not set manuscript.tex as the main document (it needs one of the two wrappers).

Submission (Routledge Submission Portal):
- anonymous.pdf -> "Manuscript - anonymous"
- authors.pdf   -> "Manuscript - with author details"
- this zip (or a zip of the Overleaf project: Menu -> Download -> Source) -> "LaTeX Source Files"

Word count printed on the title page: {total:,} words (limit 7,500 incl. tables, captions and references);
abstract {abstract} words (limit 200).
"""
    out = HERE.parent / "ijpas_overleaf.zip"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for name in ("anonymous.tex", "authors.tex", "manuscript.tex", "counts.tex"):
            z.write(HERE / name, name)
        z.write(BIB, "refs.bib")
        z.writestr("README_OVERLEAF.txt", readme)
        for p in sorted(FIGS.glob("*.pdf")):
            z.write(p, f"figures/{p.name}")
    print("Saved", out)


if __name__ == "__main__":
    main()
